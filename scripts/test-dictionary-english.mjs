import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.UI_PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.UI_TEST_URL || 'http://127.0.0.1:5193';
const out = 'docs/ai_log/dictionary-english-components';
await fs.mkdir(out, { recursive: true });
const browser = await chromium.launch({ headless: true, executablePath: process.env.UI_CHROMIUM_EXECUTABLE || undefined });
const report = [];
try {
  for (const width of [320, 375, 768, 1024, 1440]) {
    const context = await browser.newContext({ viewport: { width, height: 1000 } });
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.route('**/api/**', r => r.abort());
    await page.goto(base + '/dictionary');
    await page.waitForLoadState('networkidle');
    const data = await page.evaluate(async () => {
      const { LESSONS_DATA } = await import('/src/data/discoveryData.ts');
      const { getDeckData } = await import('/src/data/flashcardsData.ts');
      return { lessons: LESSONS_DATA.map(({id,title,category,dateAdded}) => ({id,title,category,dateAdded})), firstCard:getDeckData(LESSONS_DATA[0]).cards[0] };
    });
    const heading = page.getByRole('heading', {name:'Your vocabulary library',exact:true});
    await heading.waitFor();
    const assertLayout = async () => assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth+1), 'Overflow at '+width);
    await assertLayout();
    assert.equal(await page.locator('.vocab-deck').count(),data.lessons.length);
    assert.deepEqual(await page.locator('.vocab-deck h3').allTextContents(),data.lessons.map(x=>x.title));
    const visualSnapshot = await page.locator('.vocab-sidebar-heading').evaluate(e=>({weight:getComputedStyle(e).fontWeight,size:getComputedStyle(e).fontSize}));
    assert.equal(visualSnapshot.weight,'700');
    await page.screenshot({path:out+'/dictionary-'+width+'.png',fullPage:false,animations:'disabled'});
    const search = page.getByRole('searchbox',{name:'Search vocabulary decks'});
    await search.fill('hội an');
    assert.ok(await page.locator('.vocab-deck').count()>0);
    assert.ok((await page.locator('.vocab-results').innerText()).includes('decks found'));
    await page.getByRole('button',{name:'Clear search',exact:true}).click();
    const topics = page.getByRole('group',{name:'Filter by topic'});
    await topics.getByRole('button',{name:'Nature & landscapes',exact:true}).click();
    assert.equal(await page.locator('.vocab-deck').count(),data.lessons.filter(x=>x.category==='Nature').length);
    await topics.getByRole('button',{name:/^All/}).click();
    const sort=page.getByRole('combobox',{name:'Sort vocabulary decks'});
    await sort.selectOption('name');
    assert.deepEqual(await page.locator('.vocab-deck h3').allTextContents(),data.lessons.map(x=>x.title).sort((a,b)=>a.localeCompare(b,'en')));
    await sort.selectOption('newest');
    assert.deepEqual(await page.locator('.vocab-deck h3').allTextContents(),[...data.lessons].sort((a,b)=>b.dateAdded.localeCompare(a.dateAdded)).map(x=>x.title));
    await sort.selectOption('default');
    await search.fill('no-such-vocabulary-deck-000');
    await page.getByRole('heading',{name:'No matching decks',exact:true}).waitFor();
    await page.getByRole('button',{name:'Clear search',exact:true}).click();
    const previewTrigger=page.getByRole('button',{name:'Preview '+data.lessons[0].title,exact:true});
    await previewTrigger.click();
    const preview=page.getByRole('dialog',{name:'Vocabulary preview: '+data.lessons[0].title,exact:true});
    await preview.waitFor();
    assert.ok((await preview.innerText()).includes('Meaning: '+data.firstCard.viMeaning));
    assert.ok((await preview.innerText()).includes('Definition: '+data.firstCard.viDefinition));
    await page.evaluate(()=>{window.__spoken=[];window.speechSynthesis.cancel=()=>{};window.speechSynthesis.speak=u=>window.__spoken.push(u.text)});
    await preview.getByRole('button',{name:'Pronounce '+data.firstCard.word,exact:true}).click();
    assert.equal((await page.evaluate(()=>window.__spoken))[0],data.firstCard.word);
    for(let i=0;i<8;i++){await page.keyboard.press('Tab');assert.ok(await preview.evaluate(e=>e.contains(document.activeElement)));}
    await page.screenshot({path:out+'/preview-'+width+'.png',fullPage:true,animations:'disabled'});
    await page.keyboard.press('Escape');
    await preview.waitFor({state:'hidden'});
    assert.ok(await previewTrigger.evaluate(e=>e===document.activeElement));
    await previewTrigger.click();
    await preview.getByRole('button',{name:'Study these cards',exact:true}).click();
    await page.waitForURL('**/flashcard-study?deck='+data.lessons[0].id);
    await page.getByRole('button',{name:'Flip cards',exact:true}).waitFor();
    await page.getByRole('link',{name:'Back to vocabulary',exact:true}).click();
    await heading.waitFor();
    const addTrigger=page.getByRole('button',{name:width<1024?'Add word':'Add a word',exact:true});
    await addTrigger.click();
    const add=page.getByRole('dialog',{name:'Add a personal word',exact:true});
    await add.waitFor();
    await add.getByRole('textbox',{name:'English word',exact:true}).fill('heritage');
    await add.getByRole('textbox',{name:'Vietnamese meaning',exact:true}).fill('di sản');
    await add.getByRole('textbox',{name:'Example sentence',exact:true}).fill('We explore Vietnamese heritage.');
    await page.screenshot({path:out+'/add-word-'+width+'.png',fullPage:true,animations:'disabled'});
    await page.keyboard.press('Escape');
    await add.waitFor({state:'hidden'});
    assert.ok(await addTrigger.evaluate(e=>e===document.activeElement));
    await addTrigger.click();
    assert.equal(await add.getByRole('textbox',{name:'English word',exact:true}).inputValue(),'heritage');
    const addedAlert=page.waitForEvent('dialog').then(async d=>{const message=d.message();await d.accept();return message;});
    await add.getByRole('button',{name:'Save to library',exact:true}).click();
    assert.equal(await addedAlert,'Added "heritage" (di sản) to your vocabulary library!');
    await add.waitFor({state:'hidden'});
    await page.getByRole('button',{name:'Create your own deck',exact:false}).click();
    const create=page.getByRole('dialog',{name:'Create a vocabulary deck',exact:true});
    await create.waitFor();
    const createButton=create.getByRole('button',{name:'Create deck',exact:true});
    assert.ok(await createButton.isDisabled());
    await create.getByRole('textbox',{name:'Deck name',exact:true}).fill('Culture notes');
    await page.screenshot({path:out+'/create-deck-'+width+'.png',fullPage:true,animations:'disabled'});
    const createAlert=page.waitForEvent('dialog').then(async d=>{const message=d.message();await d.accept();return message;});
    await createButton.click();
    assert.equal(await createAlert,'Created "Culture notes" in your personal library!');
    await create.waitFor({state:'hidden'});
    await assertLayout();
    assert.deepEqual(errors,[]);
    report.push({width,decks:data.lessons.length,englishUI:true,bilingualSearch:true,filters:true,englishSort:true,previewData:true,pronunciationCallback:true,studyRoute:true,sharedAddWord:true,createDeck:true,layout:true});
    await context.close();
  }
  await fs.writeFile(out+'/report.json',JSON.stringify(report,null,2));
  console.log(JSON.stringify(report,null,2));
} finally { await browser.close(); }
