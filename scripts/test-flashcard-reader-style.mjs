import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.UI_PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.UI_TEST_URL || 'http://127.0.0.1:5193';
const out = 'docs/ai_log/flashcard-reader-style';
(async () => {
  await fs.mkdir(out, { recursive: true });
  const browser = await chromium.launch({ headless: true, executablePath: process.env.UI_CHROMIUM_EXECUTABLE || undefined });
  const report = [];
  try {
    for (const width of [320, 375, 768, 1024, 1440]) {
      const context = await browser.newContext({ viewport: { width, height: width < 768 ? 900 : 1000 } });
      const page = await context.newPage();
      const errors = [];
      page.on('pageerror', e => errors.push(e.message));
      // Keep the UI check deterministic with the project's actual local Reader vocabulary.
      await page.route('**/api/**', route => route.abort());
      await page.goto(base + '/dictionary');
      await page.waitForLoadState('networkidle');
      const cards = await page.evaluate(async () => {
        const { readerApiService } = await import('/src/features/reader/services/readerApiService.ts');
        const { cacheArticle } = await import('/src/services/learning/learningStorage.ts');
        const { studyDeckFromArticle } = await import('/src/features/flashcards/services/studyDeck.ts');
        const article = readerApiService.getLocalArticle('imperial-hue', 'Level 2');
        cacheArticle(article, 'Level 2');
        return studyDeckFromArticle(article, 'Level 2').cards;
      });
      await page.reload();
      await page.waitForLoadState('networkidle');
      assert.equal(await page.getByRole('heading', { name: 'Sổ tay từ vựng của bạn' }).count(), 0);
      const dictionarySnapshot = () => page.locator('.vocab-library-page').evaluate(el => ['.vocab-page-heading', '.vocab-actions', '.vocab-library-heading', '.vocab-category-filter', '.vocab-deck'].map(q => {
        const e = el.querySelector(q), c = getComputedStyle(e);
        return { q, text: e.textContent, font: c.font, color: c.color, background: c.backgroundColor, radius: c.borderRadius, width: e.getBoundingClientRect().width };
      }));
      const dictionaryBefore = await dictionarySnapshot();
      await page.getByRole('button', { name: width < 1024 ? 'Review' : 'Spaced review', exact: true }).click();
      await page.getByRole('button', { name: 'Flip cards', exact: true }).waitFor();
      const assertLayout = async label => {
        const layout = await page.evaluate(() => ({ viewport: innerWidth, content: document.documentElement.scrollWidth }));
        assert.ok(layout.content <= width + 1, label + ' horizontal overflow: ' + JSON.stringify(layout));
      };
      await assertLayout('Flip');
      const appearance = await page.locator('.vocab-card-front').evaluate(e => ({ radius: getComputedStyle(e).borderRadius, background: getComputedStyle(e).backgroundImage, font: getComputedStyle(e.querySelector('h3')).fontFamily, weight: getComputedStyle(e.querySelector('h3')).fontWeight }));
      assert.equal(appearance.radius, '16px');
      assert.equal(appearance.weight, '500');
      const face = page.locator('.vocab-card-front');
      assert.equal(await face.locator('.vocab-study-word').innerText(), cards[0].word);
      assert.equal(await face.locator('.vocab-context').innerText(), '“' + cards[0].contextEn + '”');
      await page.screenshot({ animations: 'disabled', path: out + '/flip-' + width + '.png', fullPage: true });
      await page.evaluate(() => { window.__spoken = []; window.speechSynthesis.cancel = () => {}; window.speechSynthesis.speak = u => window.__spoken.push({text:u.text,lang:u.lang,rate:u.rate}); });
      await page.getByRole('button', {name:'Pronounce ' + cards[0].word, exact:true}).click();
      assert.equal((await page.evaluate(() => window.__spoken))[0].text, cards[0].word);
      await page.getByRole('combobox', {name:'Pronunciation voice'}).selectOption('en-GB');
      await page.getByRole('checkbox', {name:'Auto audio'}).check();
      assert.equal((await page.evaluate(() => window.__spoken)).at(-1).lang, 'en-GB');
      await page.getByRole('checkbox', {name:'Auto audio'}).uncheck();
      const trigger = page.getByRole('button', {name:'English: ' + cards[0].word + '. Flip to see the meaning.'});
      await trigger.focus();
      await page.keyboard.press('Enter');
      assert.equal(await page.locator('.vocab-card-back').getAttribute('aria-hidden'), 'false');
      assert.equal(await page.locator('.vocab-study-meaning').innerText(), cards[0].viMeaning);
      await page.screenshot({ animations: 'disabled', path: out + '/meaning-' + width + '.png', fullPage: true });
      await page.getByRole('button', {name:'Meaning: ' + cards[0].viMeaning + '. Flip to see the English word.'}).click();
      await page.evaluate(() => { window.__random = Math.random; Math.random = () => 0; });
      await page.getByRole('button', {name:'Shuffle',exact:true}).click();
      await page.evaluate(() => { Math.random = window.__random; });
      assert.equal(await page.getByRole('button', {name:'Shuffled',exact:true}).getAttribute('aria-pressed'),'true');
      await page.getByRole('button', {name:'Shuffled',exact:true}).click();
      await page.getByRole('button', {name:'Quiz',exact:true}).click();
      await assertLayout('Quiz');
      const wrong = cards[0].options.find(x => x !== cards[0].viMeaning);
      await page.locator('.vocab-answer').filter({hasText:wrong}).click();
      assert.equal(await page.locator('.vocab-answer.is-correct').count(),1);
      assert.equal(await page.locator('.vocab-answer.is-incorrect').count(),1);
      await page.screenshot({ animations: 'disabled', path: out + '/quiz-' + width + '.png', fullPage: true });
      await page.getByRole('button', {name:'Next card',exact:true}).click();
      assert.equal(await page.getByRole('progressbar').getAttribute('aria-valuenow'),'1');
      await page.reload();
      await page.getByRole('button', {name:'Quiz',exact:true}).waitFor();
      assert.equal(await page.getByRole('progressbar').getAttribute('aria-valuenow'),'1');
      await page.getByRole('button', {name:'Spelling',exact:true}).click();
      await assertLayout('Spelling');
      const input = page.getByRole('textbox',{name:'English word',exact:true});
      await input.fill(cards[1].word);
      await input.press('Enter');
      await page.getByText('Correct! "' + cards[1].word + '"',{exact:true}).waitFor();
      await page.screenshot({ animations: 'disabled',path:out+'/spelling-'+width+'.png',fullPage:true});
      await input.press('Enter');
      await input.fill('wrong-answer');
      await page.getByRole('button',{name:'Check answer',exact:true}).click();
      await page.getByText('Not quite. The answer is: "' + cards[2].word + '"',{exact:true}).waitFor();
      await page.getByRole('button',{name:'Next card',exact:true}).click();
      await page.getByRole('region',{name:'Review summary'}).waitFor();
      await assertLayout('Summary');
      assert.ok((await page.getByRole('region',{name:'Review summary'}).innerText()).includes('1 / 3'));
      await page.screenshot({ animations: 'disabled',path:out+'/summary-'+width+'.png',fullPage:true});
      await page.getByRole('button',{name:'Review this deck again',exact:true}).click();
      assert.equal(await page.getByRole('progressbar').getAttribute('aria-valuenow'),'0');
      await page.getByRole('button',{name:'Flip cards',exact:true}).click();
      await page.getByRole('button',{name:width<1024?'Add word':'Add a word',exact:true}).click();
      const dialog = page.getByRole('dialog',{name:'Add a personal word'});
      await dialog.waitFor();
      await dialog.getByRole('textbox',{name:'English word',exact:true}).fill('heritage');
      await page.keyboard.press('Tab');
      assert.ok(await dialog.evaluate(e=>e.contains(document.activeElement)));
      await page.screenshot({ animations: 'disabled',path:out+'/add-word-'+width+'.png',fullPage:true});
      await page.keyboard.press('Escape');
      await dialog.waitFor({state:'hidden'});
      await page.evaluate(()=>document.documentElement.classList.add('dark'));
      await assertLayout('Dark');
      const darkBackground = await face.evaluate(e=>getComputedStyle(e).backgroundImage);
      assert.notEqual(darkBackground,appearance.background);
      await page.screenshot({ animations: 'disabled',path:out+'/dark-'+width+'.png',fullPage:true});
      await page.getByRole('button',{name:'Quiz',exact:true}).click();
      await page.locator('.vocab-answer').filter({hasText:cards[0].viMeaning}).click();
      assert.equal(await page.locator('.vocab-answer.is-correct').count(),1);
      assert.equal(await page.locator('.vocab-answer.is-incorrect').count(),0);
      await page.screenshot({ animations: 'disabled',path:out+'/quiz-dark-'+width+'.png',fullPage:true});
      await page.evaluate(()=>document.documentElement.classList.remove('dark'));
      await page.getByRole('link',{name:'Back to vocabulary',exact:true}).click();
      await page.waitForLoadState('networkidle');
      assert.deepEqual(await dictionarySnapshot(), dictionaryBefore, 'Dictionary appearance/content changed after study CSS loaded');
      assert.equal(await page.getByRole('heading',{name:'Sổ tay từ vựng của bạn'}).count(),0);
      await page.screenshot({ animations: 'disabled',path:out+'/dictionary-'+width+'.png',fullPage:true});
      await page.goto(base + '/flashcard-study?deck=imperial-hue&saved=1');
      await page.getByRole('heading',{name:'No vocabulary to review'}).waitFor();
      assert.ok((await page.getByRole('link',{name:'Back to the story'}).getAttribute('href')).includes('postId=imperial-hue'));
      assert.deepEqual(errors,[]);
      report.push({width,appearance,flip:true,audioCallback:true,shuffle:true,quiz:true,spelling:true,persistence:true,summary:true,restart:true,dialog:true,dark:true,dictionaryUnchanged:true,emptySaved:true});
      await context.close();
    }
    await fs.writeFile(out+'/report.json',JSON.stringify(report,null,2));
    console.log(JSON.stringify(report,null,2));
  } finally { await browser.close(); }
})().catch(e=>{ console.error(e); process.exitCode=1; });
